package gsql

import (
	"testing"

	"github.com/stretchr/testify/require"
	"google.golang.org/grpc/codes"
)

type exprCase struct {
	expr string
	want string
}

func runExprCases(t *testing.T, cases []exprCase) {
	t.Helper()
	for _, c := range cases {
		t.Run(c.expr, func(t *testing.T) {
			require.Equal(t, c.want, eval1(t, c.expr))
		})
	}
}

